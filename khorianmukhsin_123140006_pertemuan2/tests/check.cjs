// Tes logika tanpa browser atau dependensi tambahan: node tests/check.cjs
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { webcrypto } = require('node:crypto');
const nodes = new Map();
const node = (key) => { if (!nodes.has(key)) nodes.set(key, { textContent: '', disabled: false }); return nodes.get(key); };
const data = new Map();
const sandbox = { console, crypto: webcrypto, Intl, Date, setTimeout, clearTimeout, AbortController, document: { querySelector: node }, localStorage: { getItem: (key) => data.get(key) ?? null, setItem: (key, value) => data.set(key, value) } };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '../script.js'), 'utf8').replace('const app = new DashboardApp();', 'globalThis.Models = { TaskItem, DashboardApp, escapeHTML };'), sandbox);
const { TaskItem, DashboardApp, escapeHTML } = sandbox.Models;
const app = Object.create(DashboardApp.prototype);
app.key = 'test'; app.render = () => {}; app.notify = (message) => { app.message = message; };
assert.equal(app.load().length, 0);
const first = new TaskItem({ title: '  Proposal  ' });
assert.equal(first.title, 'Proposal');
assert.throws(() => new TaskItem({ title: ' ' }));
assert.throws(() => new TaskItem({ title: 'X', date: '2026-02-30' }));
assert.throws(() => new TaskItem({ title: 'X', time: '25:99' }));
assert.equal(app.commit([first]), true);
assert.equal(app.load()[0].title, 'Proposal');
const before = app.items;
app.commit(app.items.map((item) => new TaskItem({ ...item, title: 'Revisi', done: true })));
assert.equal(before[0].title, 'Proposal');
assert.equal(app.load()[0].done, true);
app.commit([...app.items, new TaskItem({ title: 'Kuliah', kind: 'schedule', done: true })]);
assert.equal(app.items[1].done, false);
app.commit(app.items.filter(({ id }) => id !== first.id));
assert.equal(app.load().length, 1);
assert.equal(escapeHTML('<img onerror="x">'), '&lt;img onerror=&quot;x&quot;&gt;');
sandbox.localStorage.setItem = () => { throw new Error('quota'); };
const saved = app.items;
assert.equal(app.commit([]), false);
assert.equal(app.items, saved);
data.set('test', '{bad');
assert.equal(app.load().length, 0);
assert.equal(app.storageBlocked, true);
(async () => {
  sandbox.fetch = async () => ({ ok: true, json: async () => ({ current_weather: { temperature: 28.4, weathercode: 3, time: '2026-10-16T21:00' } }) });
  await app.fetchWeather();
  assert.equal(node('#temperature').textContent, '28.4 °C');
  sandbox.fetch = async () => { throw new Error('offline'); };
  await app.fetchWeather();
  assert.equal(node('#temperature').textContent, '—');
  assert.equal(node('#refresh').disabled, false);
  console.log('LULUS: validasi model, tambah/edit/hapus state, persistensi, immutable update, escaping, kegagalan storage, respons cuaca sukses/gagal.');
})().catch((error) => { console.error(error); process.exitCode = 1; });
